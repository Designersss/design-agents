import assert from "node:assert/strict";
import {resolve} from "node:path";
import {pathToFileURL} from "node:url";
import {mkdirSync} from "node:fs";
import {chromium} from "playwright";

const root=resolve(import.meta.dirname,"..");
const base=pathToFileURL(resolve(root,"index.html")).href;
const artifactDir=resolve(root,"artifacts","inbox");
mkdirSync(artifactDir,{recursive:true});
const browser=await chromium.launch({headless:true});
let failed=false;
try{
 const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
 const errors=[];
 page.on("pageerror",e=>errors.push(e.message));
 await page.goto(base+"#/messages");
 await page.waitForSelector(".inbox-workspace");
 assert.equal(await page.locator("#inboxView").isVisible(),true);
 assert.equal(await page.locator("#placeholderView").isVisible(),false);
 assert.equal(await page.locator(".inbox-list-pane").isVisible(),true);
 assert.equal(await page.locator(".inbox-chat-pane").isVisible(),true);
 assert.equal(await page.locator(".inbox-context-pane").isVisible(),true);
 assert.equal(await page.locator(".inbox-thread").count(),6);
 assert.equal((await page.locator("#inboxHeading").textContent()).trim(),"Сообщения");
 assert.match(await page.locator(".inbox-live-status").innerText(),/Нужен человек/);
 const positions=await page.locator(".inbox-list-pane,.inbox-chat-pane,.inbox-context-pane").evaluateAll(e=>e.map(el=>{
  const b=el.getBoundingClientRect();return {left:b.left,right:b.right,top:b.top};
 }));
 assert.ok(positions[0].left<positions[1].left&&positions[1].left<positions[2].left);
 assert.ok(positions.every(p=>Math.abs(p.top-positions[0].top)<2));
 await page.screenshot({path:resolve(artifactDir,"inbox-desktop.png"),fullPage:true});
 await page.locator('[data-inbox-action="take"]').click();
 assert.match(await page.locator(".inbox-live-status").innerText(),/У сотрудника/);
 assert.equal(await page.locator("#inboxCompose").isEnabled(),true);
 await page.locator("#inboxCompose").fill("Здравствуйте, Анна! Я подключился к разговору.");
 await page.locator('[data-inbox-form] button[type="submit"]').click();
 assert.match(await page.locator(".inbox-messages").innerText(),/Я подключился к разговору/);
 assert.equal(await page.locator("#inboxCompose").inputValue(),"");
 await page.reload();
 await page.waitForSelector(".inbox-workspace");
 assert.match(await page.locator(".inbox-live-status").innerText(),/У сотрудника/);
 assert.match(await page.locator(".inbox-messages").innerText(),/Я подключился к разговору/);
 await page.locator('[data-inbox-action="return"]').click();
 assert.match(await page.locator(".inbox-live-status").innerText(),/Отвечает агент/);
 assert.equal(await page.locator("#inboxCompose").isDisabled(),true);
 await page.locator('[data-inbox-filter="waiting"]').click();
 assert.equal(await page.locator(".inbox-thread").count(),1);
 assert.match(await page.locator(".inbox-thread").innerText(),/Ольга Соколова/);
 await page.locator('[data-inbox-filter="all"]').click();
 await page.locator("[data-inbox-search]").fill("Михаил");
 assert.equal(await page.locator(".inbox-thread").count(),1);
 assert.match(await page.locator(".inbox-thread").innerText(),/Михаил Петров/);
 await page.locator("[data-inbox-search]").fill("");
 await page.locator('[data-inbox-open="support-maksim"]').click();
 assert.match(await page.locator(".inbox-context-pane").innerText(),/Битрикс24/);
 assert.equal(await page.locator("#inboxCompose").isEnabled(),true);
 await page.screenshot({path:resolve(artifactDir,"inbox-handoff-desktop.png"),fullPage:true});
 await page.goto(base+"#/agent/leads/messages");
 await page.waitForSelector(".inbox-workspace");
 assert.equal((await page.locator("#inboxHeading").innerText()).trim(),"Диалоги");
 assert.equal(await page.locator(".inbox-thread").count(),2);
 assert.equal(await page.locator(".agent-nav").isVisible(),true);
 assert.equal(await page.locator(".global-nav").isVisible(),false);
 assert.match(await page.locator(".inbox-list-pane").innerText(),/Анна Ковалева/);
 assert.doesNotMatch(await page.locator(".inbox-list-pane").innerText(),/Максим Орлов/);
 await page.screenshot({path:resolve(artifactDir,"agent-dialogs-desktop.png"),fullPage:true});
 await page.goto(base+"#/agent/support/messages");
 await page.waitForSelector(".inbox-workspace");
 assert.equal(await page.locator(".inbox-thread").count(),2);
 assert.match(await page.locator(".inbox-list-pane").innerText(),/Максим Орлов/);

 await page.setViewportSize({width:390,height:844});
 await page.goto(base+"#/messages");
 await page.waitForSelector(".inbox-workspace");
 assert.equal(await page.locator(".inbox-list-pane").isVisible(),true);
 assert.equal(await page.locator(".inbox-chat-pane").isVisible(),false);
 const mobileWidth=await page.evaluate(()=>({width:document.documentElement.scrollWidth,viewport:innerWidth}));
 assert.ok(mobileWidth.width<=mobileWidth.viewport+2,"Inbox overflows mobile: "+JSON.stringify(mobileWidth));
 await page.screenshot({path:resolve(artifactDir,"inbox-mobile-list.png"),fullPage:true});
 await page.locator('[data-inbox-open="lead-anna"]').click();
 assert.equal(await page.locator(".inbox-list-pane").isVisible(),false);
 assert.equal(await page.locator(".inbox-chat-pane").isVisible(),true);
 await page.screenshot({path:resolve(artifactDir,"inbox-mobile-chat.png"),fullPage:true});
 await page.locator("[data-inbox-context]").click();
 assert.equal(await page.locator(".inbox-context-pane").isVisible(),true);
 assert.match(await page.locator(".inbox-context-pane").innerText(),/amoCRM/);
 await page.screenshot({path:resolve(artifactDir,"inbox-mobile-context.png"),fullPage:true});
 await page.locator("[data-inbox-context-close]").click();
 assert.equal(await page.locator(".inbox-context-pane").isVisible(),false);
 await page.locator("[data-inbox-back]").click();
 assert.equal(await page.locator(".inbox-list-pane").isVisible(),true);
 const mobileWidthAfter=await page.evaluate(()=>({width:document.documentElement.scrollWidth,viewport:innerWidth}));
 assert.ok(mobileWidthAfter.width<=mobileWidthAfter.viewport+2,"Inbox overflows after navigation: "+JSON.stringify(mobileWidthAfter));
 assert.deepEqual(errors,[],"No runtime errors");
 console.log("Inbox design browser checks passed");
}catch(error){failed=true;console.error(error)}
finally{await browser.close()}
if(failed)process.exitCode=1;
